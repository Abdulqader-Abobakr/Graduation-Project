<?php

namespace App\Http\Controllers;

use Illuminate\Http\Request;
use Illuminate\Support\Facades\Http;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Log;

class PlatformAssistantController extends Controller
{
    public function ask(Request $request)
    {
        $request->validate([
            'message' => 'required|string|max:1000',
            'history' => 'nullable|array',
        ]);

        $user = $request->user();
        $userMessage = trim($request->input('message'));
        $chatHistory = $request->input('history', []);
        $role = $user ? ($user->role ?? '') : '';

        // 1. قراءة الدليل الهيكلي للمنصة
        $guidePath = resource_path('markdown/sila_guide.md');
        $guideContent = File::exists($guidePath) ? File::get($guidePath) : '';

        // 2. تزويد الذكاء الاصطناعي ببيانات المستخدم الحالي لتخصيص الإجابة
        $isCompanyUser = ($user && ($user->role === 'client_company' || $user->role === 'company'));
        $roleName = $isCompanyUser ? 'رائد أعمال / شركة' : 'خبير مستقل';
        $verifiedName = ($user && $user->account_state === 'verified') ? 'موثق' : 'غير موثق';

        $roleConstraintText = $isCompanyUser
            ? "   - المستخدم الحالي هو [رائد أعمال / شركة]. تقتصر إجاباتك حصراً على واجهات وإجراءات رواد الأعمال (استكشف، الطلبات والعروض، مشاريعي، مساحة العمل لمراجعة واعتماد التسليمات أو طلب تعديل، صفحة إتمام الدفع وسداد الضمان المالي، المحادثات، والملف التعريفي).\n"
            . "   - يُمنع منعاً باتاً تقديم أي خطوات أو شرح لواجهات تخص جانب الخبراء ومزودي الخدمة (مثل: تقديم العروض، سحب الأرباح، إدارة واجهة خدماتي، إضافة عمل للمعرض، رفع تسليمات المراحل).\n"
            . "   - إذا سأل المستخدم عن ميزة أو إجراء يخص الخبير (مثل: 'كيف أقدم عرض سعر؟'، 'كيف أسحب أرباحي؟'، 'كيف أضيف عمل للمعرض؟'، 'كيف أرفع تسليم؟'): ارفض تقديم خطوات الخبير بلطف، ووضّح له أن هذه الميزة خاصة بالخبراء فقط ولا تتوفر في حسابه كرائد أعمال، ووجّهه لما يناسب دوره كرائد أعمال.\n"
            : "   - المستخدم الحالي هو [خبير مستقل]. تقتصر إجاباتك حصراً على واجهات وإجراءات الخبراء المستقلين (الرئيسية، العروض والطلبات، مشاريعي، مساحة العمل لرفع التسليمات، خدماتي وإدارة التخصصات والمعرض، الأرباح وسحب الرصيد، المحادثات، والملف الشخصي).\n"
            . "   - يُمنع منعاً باتاً تقديم أي خطوات أو شرح لواجهات تخص جانب رواد الأعمال والشركات (مثل: طرح مشروع جديد، سداد الضمان المالي، قبول العروض، اعتماد التسليم النهائي، طلب تعديل).\n"
            . "   - إذا سأل المستخدم عن ميزة أو إجراء يخص رواد الأعمال (مثل: 'كيف أطرح مشروع جديد؟'، 'كيف أسدد الضمان؟'، 'كيف أقبل عرض سعر؟'، 'كيف أعتمد التسليم؟'): ارفض تقديم خطوات رائد الأعمال بلطف، ووضّح له أن هذه الميزة خاصة برواد الأعمال والشركات فقط ولا تتوفر في حسابه كخبير مستقل، ووجّهه لما يناسب دوره كخبير.\n";

        $userContext = "بيانات المستخدم الحالي:\n"
            . "- الاسم: " . ($user->user_name ?? 'مستخدم') . "\n"
            . "- الدور: " . $roleName . "\n"
            . "- حالة التوثيق: " . $verifiedName . "\n\n"
            . "تعليمات صارمة للرد:\n"
            . "1. العزل الصارم لمجال المستخدم (Strict Role Scoping) - قاعدة حاسمة:\n"
            . $roleConstraintText
            . "2. الحظر التام للروابط والمسارات البرمجية:\n"
            . "   - يُمنع منعاً باتاً كتابة أي روابط أو مسارات برمجية إنجليزية مثل مسارات النظام نهائياً في أي رد، واكتفِ فقط بالاسم العربي للواجهة والزر.\n"
            . "3. التمييز الصارم بين الأسئلة الواضحة وغير الواضحة:\n"
            . "   - إذا كان سؤال المستخدم واضحاً ومحدداً وضمن مجال دوره:\n"
            . "     * ابدأ إجابتك فوراً بذكر اسم الواجهة المحددة في القائمة الجانبية باللغة العربية (مثال: 'اذهب إلى واجهة **مشاريعي** من القائمة الجانبية:').\n"
            . "     * قدّم الخطوات العملية المتبقية على شكل نقاط مرقمة وواضحة (1، 2، 3...).\n"
            . "   - إذا كان السؤال غير واضح، أو مبهماً، أو ناقصاً، أو عاماً جداً، أو مجرد تحية، أو خارج نطاق المنصة:\n"
            . "     * يُمنع منعاً باتاً ذكر أي واجهات، أو مسارات، أو خطوات، أو ميزات للمنصة (لا تجب بأي شيء من المنصة إطلاقاً).\n"
            . "     * لا تخمّن ما يقصده المستخدم ولا تسرد له قائمة واجهات المنصة.\n"
            . "     * رد فقط بجملة وجيزة مهذبة تطلب منه توضيح استفساره وتحديد ما يريد فعله داخل المنصة، أو رد التحية بلطف واطلب طرح سؤاله بوضوح.\n\n";

        $systemInstruction = $guideContent . "\n\n" . $userContext;

        // 3. تجهيز تاريخ المحادثة بشكل يتوافق بدقة مع شروط Gemini API
        $contents = [];
        $lastRole = null;

        foreach ($chatHistory as $msg) {
            $text = trim($msg['text'] ?? '');
            if (empty($text)) continue;

            $msgRole = ($msg['sender'] === 'user') ? 'user' : 'model';

            // الشرط 1: محادثة Gemini يجب أن تبدأ دائماً بـ user
            if (empty($contents) && $msgRole !== 'user') {
                continue; // تجاهل أي ترحيب افتراضي من الموديل في البداية
            }

            // الشرط 2: عدم تكرار نفس الـ role مرتين متتاليتين
            if ($msgRole === $lastRole) {
                $lastIndex = count($contents) - 1;
                $contents[$lastIndex]['parts'][0]['text'] .= "\n" . $text;
                continue;
            }

            $contents[] = [
                'role' => $msgRole,
                'parts' => [['text' => $text]]
            ];
            $lastRole = $msgRole;
        }

        // إضافة رسالة المستخدم الحالية
        if ($lastRole === 'user' && !empty($contents)) {
            $lastIndex = count($contents) - 1;
            $contents[$lastIndex]['parts'][0]['text'] .= "\n" . $userMessage;
        } else {
            $contents[] = [
                'role' => 'user',
                'parts' => [['text' => $userMessage]]
            ];
        }

        // 4. قراءة مفتاح الـ API
        $apiKey = config('services.gemini.key') ?: env('GEMINI_API_KEY');

        // إذا كان المفتاح متوفراً، نحاول الاتصال بـ Gemini
        if (!empty($apiKey)) {
            $modelsToTry = array_unique(array_filter([
                config('services.gemini.model'),
                'gemini-2.5-flash',
                'gemini-2.0-flash',
                'gemini-1.5-flash',
                'gemini-1.5-flash-8b',
            ]));

            $payload = [
                'system_instruction' => [
                    'parts' => [['text' => $systemInstruction]]
                ],
                'contents' => $contents,
                'generationConfig' => [
                    'temperature' => 0.2,
                    'maxOutputTokens' => 700,
                ],
            ];

            foreach ($modelsToTry as $model) {
                $endpoint = "https://generativelanguage.googleapis.com/v1beta/models/{$model}:generateContent?key={$apiKey}";
                try {
                    $response = Http::timeout(15)->post($endpoint, $payload);

                    if ($response->successful()) {
                        $data = $response->json();
                        $reply = $data['candidates'][0]['content']['parts'][0]['text'] ?? null;

                        if ($reply) {
                            return response()->json([
                                'success' => true,
                                'reply' => $reply
                            ]);
                        }
                    }

                    $errorBody = $response->json();
                    $lastErrorMessage = $errorBody['error']['message'] ?? $response->body();
                    Log::warning("PlatformAssistant: Model [{$model}] failed (HTTP {$response->status()}): {$lastErrorMessage}");
                } catch (\Exception $e) {
                    Log::error("PlatformAssistant exception with model [{$model}]: " . $e->getMessage());
                }
            }
        }

        // 5. في حال عدم وجود مفتاح أو تعذر الاتصال بـ Gemini، نستخدم الدليل المباشر الذكي كبديل فوري مضمون
        $fallbackReply = $this->getFallbackReply($userMessage, $role);

        return response()->json([
            'success' => true,
            'reply' => $fallbackReply
        ]);
    }

    /**
     * إجابة فورية ذكية مستخرجة مباشرة من دليل منصة صلة
     */
    protected function getFallbackReply(string $query, string $role): string
    {
        $q = mb_strtolower(trim($query));
        $isCompany = ($role === 'client_company' || $role === 'company');

        // 1. التعامل مع التحية والترحيب العادي (عدم ذكر أي واجهات أو خطوات للمنصة)
        $greetings = ['مرحبا', 'مرحباً', 'سلام', 'السلام عليكم', 'أهلا', 'أهلاً', 'اهلا', 'هلا', 'صباح الخير', 'مساء الخير', 'هاي', 'hello', 'hi'];
        foreach ($greetings as $greeting) {
            if ($q === $greeting || str_starts_with($q, $greeting . ' ') || str_starts_with($q, $greeting . '!') || str_starts_with($q, $greeting . '،')) {
                return "أهلاً بك! أنا مساعد منصة صِلة الذكي. تفضل بطرح استفسارك بوضوح حول ما ترغب في معرفته أو تنفيذه لأتمكن من إرشادك بالخطوات الدقيقة.";
            }
        }

        // توحيد الحروف العربية لمطابقة دقيقة ومرنة
        $nq = str_replace(['أ', 'إ', 'آ'], 'ا', $q);
        $nq = str_replace('ة', 'ه', $nq);
        $nq = str_replace('ى', 'ي', $nq);

        // 2. تطبيق العزل الصارم لمجال المستخدم (Strict Role Scoping)
        // أ. إذا كان المستخدم رائد أعمال وسأل عن إجراءات أو صفحات الخبير ومزود الخدمة
        if ($isCompany) {
            $isFreelancerAction = (
                (!str_contains($nq, 'قبول') && !str_contains($nq, 'استعراض') && !str_contains($nq, 'مراجعه') && (str_contains($nq, 'تقديم عرض') || str_contains($nq, 'اقدم عرض') || str_contains($nq, 'ارسل عرض') || str_contains($nq, 'ارسال عرض'))) ||
                str_contains($nq, 'ارباح') ||
                str_contains($nq, 'سحب رصيد') ||
                str_contains($nq, 'خدماتي') ||
                str_contains($nq, 'معرض') ||
                str_contains($nq, 'اعمالي') ||
                str_contains($nq, 'رفع تسليم') ||
                str_contains($nq, 'ارفع تسليم') ||
                str_contains($nq, 'ارسال تسليم')
            );

            if ($isFreelancerAction) {
                return "هذه الميزة مخصصة لحسابات الخبراء فقط، ولا تتوفر في حسابك كرائد أعمال. بصفتك رائد أعمال، يمكنك طرح المشاريع من واجهة **الطلبات والعروض**، ومراجعة العروض المستلمة وقبولها، وسداد الضمان المالي، ومتابعة تسليمات مشاريعك واعتمادها من واجهة **مشاريعي**.";
            }
        }

        // ب. إذا كان المستخدم خبيراً مستقلاً وسأل عن إجراءات أو صفحات رائد الأعمال
        if (!$isCompany) {
            $isCompanyAction = (
                str_contains($nq, 'طرح') ||
                str_contains($nq, 'مشروع جديد') ||
                str_contains($nq, 'طلب جديد') ||
                str_contains($nq, 'انشاء طلب') ||
                str_contains($nq, 'انشر') ||
                str_contains($nq, 'اسوي طلب') ||
                str_contains($nq, 'ضمان') ||
                str_contains($nq, 'سداد') ||
                str_contains($nq, 'سدد') ||
                str_contains($nq, 'تسديد') ||
                str_contains($nq, 'ايصال') ||
                str_contains($nq, 'قبول عرض') ||
                str_contains($nq, 'اقبل عرض') ||
                str_contains($nq, 'استكشف') ||
                str_contains($nq, 'اعتمد التسليم') ||
                str_contains($nq, 'اعتماد التسليم') ||
                str_contains($nq, 'طلب تعديل')
            );

            if ($isCompanyAction) {
                return "هذه الميزة مخصصة لحسابات رواد الأعمال والشركات فقط، ولا تتوفر في حسابك كخبير مستقل. بصفتك خبيراً، يمكنك تصفح المشاريع المتاحة وتقديم عروض أسعار منافسة من واجهة **العروض والطلبات**، أو متابعة مراحل مشاريعك النشطة ورفع التسليمات من واجهة **مشاريعي**.";
            }
        }

        // 3. الأسئلة العامة حول استخدام المنصة وبدء العمل حسب الدور
        if (str_contains($nq, 'استخدام المنصه') || str_contains($nq, 'استخدم المنصه') || str_contains($nq, 'كيف ابدا')) {
            if ($isCompany) {
                return "أهلاً بك! يمكنك كرائد أعمال استخدام المنصة بالخطوات التالية:\n1. **طرح مشروع جديد:** من واجهة **الطلبات والعروض** بالضغط على زر 'طلب جديد'.\n2. **استكشاف الخبراء:** من واجهة **استكشف** للبحث عن الخبراء الموثقين ومحادثتهم.\n3. **متابعة المشاريع وإيداع الضمان:** من واجهة **مشاريعي** وصفحة **إتمام الدفع** حيث تسدد قيمة المشروع وتتابع التسليمات وتعتمدها أو تطلب تعديلاً.\n4. **المحادثات المباشرة:** من واجهة **المحادثات** للتواصل السريع مع الخبير.";
            } else {
                return "أهلاً بك! يمكنك كخبير استخدام المنصة بالخطوات التالية:\n1. **تقديم العروض:** من واجهة **العروض والطلبات** للتنافس على المشاريع المطروحة.\n2. **تنفيذ المشاريع ومساحة العمل:** من واجهة **مشاريعي** لرفع تسليمات المراحل والتواصل.\n3. **إبراز مهاراتك:** من واجهة **خدماتي** لإضافة أعمالك في المعرض وتحديد تخصصاتك وحالة تواجدك.\n4. **متابعة وسحب الأرباح:** من واجهة **الأرباح** عبر تحويل بنكي أو محفظة جيب أو حوالة محلية.";
            }
        }

        // 4. إجراءات خاصة برائد الأعمال (Company Side)
        if ($isCompany) {
            // طرح مشروع أو إدارة الطلبات
            if (str_contains($nq, 'طرح') || str_contains($nq, 'مشروع جديد') || str_contains($nq, 'طلب جديد') || str_contains($nq, 'انشاء طلب') || str_contains($nq, 'اسوي') || str_contains($nq, 'انشر') || str_contains($nq, 'طلباتي')) {
                return "اذهب إلى واجهة **الطلبات والعروض** من القائمة الجانبية:\n1. اضغط على زر **'طلب جديد'** في أعلى الواجهة.\n2. املأ عنوان الطلب، نوع الخدمة (تسويق، تصميم، برمجة، تحليلات، محتوى)، وتوجيه الطلب (عام لكافة الخبراء أو خاص بخبير محدد)، وتفاصيل وشروط المشروع.\n3. اضغط على **'حفظ ونشر'** وسيظهر طلبك فوراً للخبراء لتقديم عروضهم.\n(ملاحظة: يمكنك تعديل أو حذف الطلب طالما لم يستلم أي عرض سعر بعد).";
            }

            // سداد الضمان المالي
            if (str_contains($nq, 'ضمان') || str_contains($nq, 'حجز') || str_contains($nq, 'دفع') || str_contains($nq, 'تحويل') || str_contains($nq, 'ايصال') || str_contains($nq, 'سداد') || str_contains($nq, 'سدد') || str_contains($nq, 'تسديد') || str_contains($nq, 'قيمه المشروع')) {
                return "بخصوص الضمان المالي وسداد قيمة المشروع:\n1. فور قبولك لعرض الخبير المناسب، ينقلك النظام تلقائياً إلى صفحة **إتمام الدفع** (أو من بطاقة المشروع في واجهة **مشاريعي**).\n2. يتم تحويل مبلغ المشروع بالريال اليمني للمسؤول المالي: اسامة حلمي علي الدبعي (775663444) عبر إحدى الوسائل الثلاث (التحويل عبر شبكة صرافة محلية، محفظة إلكترونية، أو بنك الكريمي).\n3. ارفع صورة سند التحويل واضغط **'تأكيد وإرسال السند'**.\n4. بعد اعتماد الإيصال من المشرف، يتفعل المشروع ويُحجز المبلغ في **'الرصيد المعلق'** لمحفظة الخبير كضمان آمن لا يتحرر إلا بعد موافقتك النهائية على اكتمال المشروع بنسبة 100%.";
            }

            // متابعة المشاريع ومساحة العمل واعتماد التسليم
            if (str_contains($nq, 'تسليم') || str_contains($nq, 'مراجعه') || str_contains($nq, 'تعديل') || str_contains($nq, 'متابعه') || str_contains($nq, 'مشاريعي') || str_contains($nq, 'مساحه العمل')) {
                return "اذهب إلى واجهة **مشاريعي** من القائمة الجانبية:\n1. اضغط على المشروع النشط للدخول إلى **'مساحة العمل' (Workspace)**.\n2. استعرض تسليمات المراحل المرفوعة وعاين الملفات أو حمّلها واطلع على الروابط الخارجية.\n3. اضغط **'اعتماد التسليم'** لتأكيد المرحلة (وعند اعتماد آخر تسليم يكتمل المشروع بنسبة 100% ويتحرر المبلغ فوراً لرصيد الخبير المتاح وتنتقل ملكية المخرجات كاملة لك)، أو اضغط **'طلب تعديل'** لإرسال ملاحظاتك؛ حيث ينقص عداد التعديلات المتبقية بمقدار (1) حتى يصل للصفر.";
            }

            // مراجعة العروض وقبولها
            if (str_contains($nq, 'عرض') || str_contains($nq, 'عروض') || str_contains($nq, 'قبول')) {
                return "اذهب إلى واجهة **الطلبات والعروض** من القائمة الجانبية:\n1. اضغط على عنوان الطلب لمشاهدة جميع العروض المستلمة من الخبراء.\n2. ستظهر تفاصيل العرض: السعر الإجمالي بالريال اليمني، المدة، سقف التعديلات، والمراحل المقترحة.\n3. يمكنك الضغط على **'بدء محادثة'** للتفاوض، أو **'قبول العرض'** للانتقال إلى صفحة **إتمام الدفع** وتأكيد الضمان المالي، أو **'رفض العرض'**.";
            }

            // استكشاف الخبراء
            if (str_contains($nq, 'استكشف') || str_contains($nq, 'مستقل') || str_contains($nq, 'خبير')) {
                return "اذهب إلى واجهة **استكشف** من القائمة الجانبية:\n1. استعرض تخصصات التسويق والبرمجة والتصميم والاستشارات.\n2. استخدم شريط البحث والفلترة لتصفح ملفات الخبراء الموثقين وتقييماتهم ومعارض أعمالهم.\n3. يمكنك بدء محادثة مباشرة أو دعوة الخبير لتقديم عرض على مشروعك.";
            }
        }

